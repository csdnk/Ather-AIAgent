from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def sized_text(seed: str, length: int) -> str:
    if not seed:
        raise ValueError("seed must not be empty")
    return (seed * (length // len(seed) + 1))[:length]


