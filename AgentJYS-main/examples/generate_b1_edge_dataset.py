def main() -> None:
    parser = argparse.ArgumentParser(description="Generate comprehensive B1 boundary data")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("runtime/b1/b1-edge-dataset.jsonl"),
    )
    args = parser.parse_args()
    records = build_records()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8", newline="\n") as stream:
        for record in records:
            stream.write(json.dumps(record, ensure_ascii=False, separators=(",", ":")))
            stream.write("\n")
    print(
        json.dumps(
            {
                "output": str(args.output.resolve()),
                "records": len(records),
                "valid_sidecar_inputs": 10,
                "expected_sidecar_failures": 1,
                "expected_local_validation_failures": 4,
                "maximum_text_chars": max(len(record["text"]) for record in records),
            },
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
